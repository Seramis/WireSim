// SDL ref-counts its own subsystems, but concurrent Init/Quit calls from
// several Mrdi1 render threads racing the refcount is still undefined
// behaviour, so serialize it here too. See Mrdi1.md ("Threading model")
// for why each render thread pumps its own SDL events instead of
// sharing an event-pump thread.
std::mutex g_sdlMutex;
int g_sdlRefCount = 0;

void SdlAcquire() {
	std::lock_guard lock(g_sdlMutex);
	if (g_sdlRefCount++ == 0) {
		SDL_SetHint(SDL_HINT_RENDER_SCALE_QUALITY, "nearest");
		SDL_InitSubSystem(SDL_INIT_VIDEO);
	}
}

void SdlRelease() {
	std::lock_guard lock(g_sdlMutex);
	if (--g_sdlRefCount == 0) {
		SDL_QuitSubSystem(SDL_INIT_VIDEO);
	}
}


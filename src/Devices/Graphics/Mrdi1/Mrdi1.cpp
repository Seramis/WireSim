Mrdi1::Mrdi1(Sim::Platform* p, std::string name) :
	Pins{
		Sim::Bus::New(p, 8, name + ".D"),
		Sim::Pin::New(p, name + ".A0"),
		Sim::Pin::New(p, name + ".NotCE"),
		Sim::Pin::New(p, name + ".NotWE")
	},
	_diagnostics(p->GetDiagnostics()), _name(std::move(name)), _vram(VramSize, 0), _textVram(TextSize, 0),
	_textAttr(TextSize, 0) {
	Pins.NotWE.AddTrigger(this, CTRL::NotWE, false);

	_renderThread = std::thread(&Mrdi1::RenderLoop, this);
}

Mrdi1::~Mrdi1() {
	_stopRequested = true;
	{
		std::lock_guard lock(_openMutex);
		_openRequested = true; // wake RenderLoop if it's waiting to open
	}
	_openCv.notify_all();
	if (_renderThread.joinable()) _renderThread.join();
}

void Mrdi1::OpenWindow() {
	if (_windowOpen.load()) return;
	{
		std::lock_guard lock(_openMutex);
		_openRequested = true;
	}
	_openCv.notify_all();
}

void Mrdi1::Logic(Sim::TriggerMask) {
	const auto isWrite = Pins.NotCE.IsLow() && Pins.NotWE.IsLow();
	const auto isWriteDone = !isWrite && _lastIsWrite;
	_lastIsWrite = isWrite;

	if (isWriteDone) {
		CommitWrite(_lastA0, _lastData);
	}

	if (isWrite) {
		_lastA0 = Pins.A0.IsHigh();
		_lastData = Pins.D.Read<uint8_t>();
	}

	Pins.D.Clear(); // write-only device: never drives the data bus
}

void Mrdi1::CommitWrite(bool a0, uint8_t data) {
	if (!a0) {
		// IR write: (re)start the instruction cycle (see Mrdi1.md).
		_opcode = data;
		_state = FsmState::ExpectAddrLow;
		_diagnostics.Println("{} IR <- {:02x}", _name, data);
		return;
	}

	switch (_state) {
		case FsmState::ExpectAddrLow:
			_vramPtr = data;
			_state = FsmState::ExpectAddrHigh;
			break;
		case FsmState::ExpectAddrHigh:
			_vramPtr = static_cast<uint16_t>((_vramPtr | (uint16_t(data) << 8)) % BufferSizeFor(_opcode));
			_state = FsmState::Streaming;
			break;
		case FsmState::Streaming: {
			const uint16_t size = BufferSizeFor(_opcode);
			{
				std::lock_guard lock(_vramMutex);
				switch (_opcode) {
					case OpDrawPixels: _vram[_vramPtr] = data; break;
					case OpWriteText: _textVram[_vramPtr] = data; break;
					case OpTextAttr: _textAttr[_vramPtr] = data; break;
					default: break; // unknown opcode: drop the stream byte
				}
			}
			_vramDirty = true;
			_vramPtr = static_cast<uint16_t>((_vramPtr + 1) % size);
			break;
		}
	}
}

uint16_t Mrdi1::BufferSizeFor(uint8_t opcode) {
	switch (opcode) {
		case OpWriteText:
		case OpTextAttr: return TextSize;
		default: return VramSize; // OpDrawPixels and any unknown opcode
	}
}

void Mrdi1::RenderLoop() {
	SdlAcquire();

	// Outer loop: idle (no window) until OpenWindow() is called, then run
	// the window until it's closed (by the user or by ~Mrdi1), then go
	// back to idle. See Mrdi1.md's "Threading model" for why the window
	// doesn't open at construction.
	while (!_stopRequested) {
		{
			std::unique_lock lock(_openMutex);
			_openCv.wait(lock, [this] {
				return _openRequested || _stopRequested;
			});
			_openRequested = false;
		}
		if (_stopRequested) break;

		SDL_Window* window = SDL_CreateWindow(
			_name.c_str(), SDL_WINDOWPOS_UNDEFINED, SDL_WINDOWPOS_UNDEFINED, Width * 2, Height * 2, SDL_WINDOW_RESIZABLE
		);
		SDL_Renderer* renderer = window ? SDL_CreateRenderer(window, -1, SDL_RENDERER_ACCELERATED) : nullptr;
		SDL_Texture* texture =
			renderer ? SDL_CreateTexture(renderer, SDL_PIXELFORMAT_RGBA8888, SDL_TEXTUREACCESS_STREAMING, Width, Height)
					 : nullptr;

		if (!window || !renderer || !texture) {
			std::println("{}: failed to create SDL window ({})", _name, SDL_GetError());
			if (texture) SDL_DestroyTexture(texture);
			if (renderer) SDL_DestroyRenderer(renderer);
			if (window) SDL_DestroyWindow(window);
			continue;
		}

		// Scale the 320x200 framebuffer to the (resizable) window with
		// nearest-neighbour filtering (the hint set in SdlAcquire()).
		SDL_RenderSetLogicalSize(renderer, Width, Height);

		std::vector<uint32_t> pixels(Width * Height);
		std::vector<uint8_t> localVram(VramSize, 0);
		std::vector<uint8_t> localText(TextSize, 0);
		std::vector<uint8_t> localAttr(TextSize, 0);
		bool closed = false;
		_windowOpen = true;
		const Uint32 windowID = SDL_GetWindowID(window);
		// _vramDirty only latches on new writes; force a repaint of
		// whatever is already in _vram, since this window's texture
		// starts blank (and reopening doesn't re-trigger CommitWrite).
		_vramDirty = true;

		while (!_stopRequested && !closed) {
			for (const SDL_Event& event : SdlEventHub::PollEventsFor(windowID)) {
				if (event.type == SDL_QUIT) closed = true;
				if (event.type == SDL_WINDOWEVENT && event.window.event == SDL_WINDOWEVENT_CLOSE &&
					event.window.windowID == windowID)
					closed = true;
			}

			if (_vramDirty.exchange(false)) {
				{
					std::lock_guard lock(_vramMutex);
					localVram = _vram;
					localText = _textVram;
					localAttr = _textAttr;
				}
				for (int i = 0; i < Width * Height; ++i) {
					const uint8_t byte = localVram[i / 8];
					const int bitOffset = 7 - (i % 8);
					const bool on = (byte >> bitOffset) & 1;
					pixels[i] = on ? 0xFFFFFFFFu : 0x000000FFu; // RGBA8888
				}

				// Text layer, composited in front of the pixel layer: a
				// code outside printable ASCII (0x20-0x7E) draws nothing,
				// leaving the pixel layer visible through the cell. Only
				// ink pixels are ever drawn -- the background is always
				// transparent, in both normal and AttrInvert cells. Invert
				// just recolors the ink from white to black; it never fills
				// the cell.
				for (int cell = 0; cell < TextSize; ++cell) {
					const uint8_t ch = localText[cell];
					if (ch < 0x20 || ch > 0x7E) continue;
					const uint8_t* glyph = Font8x8[ch - 0x20];
					const bool invert = (localAttr[cell] & AttrInvert) != 0;
					const uint32_t inkColor = invert ? 0x000000FFu : 0xFFFFFFFFu;
					const int baseX = (cell % TextCols) * CharWidth;
					const int baseY = (cell / TextCols) * CharHeight;
					for (int ry = 0; ry < CharHeight; ++ry) {
						const uint8_t bits = glyph[ry];
						for (int rx = 0; rx < CharWidth; ++rx) {
							if (!((bits >> (7 - rx)) & 1)) continue; // transparent background
							pixels[(baseY + ry) * Width + (baseX + rx)] = inkColor;
						}
					}
				}

				SDL_UpdateTexture(texture, nullptr, pixels.data(), Width * static_cast<int>(sizeof(uint32_t)));
			}

			SDL_RenderClear(renderer);
			SDL_RenderCopy(renderer, texture, nullptr, nullptr);
			SDL_RenderPresent(renderer);

			std::this_thread::sleep_for(std::chrono::milliseconds(16));
		}

		_windowOpen = false;
		SDL_DestroyTexture(texture);
		SDL_DestroyRenderer(renderer);
		SDL_DestroyWindow(window);
		SdlEventHub::Forget(windowID);
	}

	SdlRelease();
}
